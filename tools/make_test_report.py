#!/usr/bin/env python3
"""Runs the test suite and generates TEST_REPORT.md from the real results (nothing is hand-typed).

    python tools/make_test_report.py        (needs pytest in the active environment)
"""
import json
import platform
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

REQUIREMENTS = [
    (1, "Normal generation at 40-55 tok/s", ["test_normal_generation_40_55_never_alerts"]),
    (2, "Legitimate tool calls at 50-71 tok/s", ["test_legitimate_tool_call_generation_50_71_stays_normal"]),
    (3, "Short 80+ tok/s block", ["test_short_80_plus_block_is_ignored_by_rolling_window",
                                  "test_single_fast_block_on_a_fresh_session_has_insufficient_data",
                                  "test_sustained_critical_speed_is_only_an_indicator"]),
    (4, "Tiny-block speed artifacts (and prefill != generation)", ["test_tiny_block_artifacts_are_ignored",
                                                                   "test_prefill_throughput_is_not_generation_speed"]),
    (5, "Long repeated text", ["test_long_repeated_text_is_detected", "test_fingerprint_is_stable_across_rotations",
                               "test_short_period_loop_is_detected", "test_detection_survives_arbitrary_chunk_boundaries"]),
    (6, "Repeated tool calls", ["test_same_file_read_repeatedly_without_progress", "test_identical_edit_repeated",
                                "test_same_search_repeated", "test_action_response_cycle"]),
    (7, "Repeated failed commands", ["test_repeated_failed_command_identical_error",
                                     "test_failed_command_with_changing_errors_is_only_a_warning",
                                     "test_whitespace_and_volatile_args_do_not_hide_repetition"]),
    (8, "Legitimate repeated code structures (and other false-positive guards)",
     ["test_legitimate_repeated_code_structures_are_not_flagged", "test_identical_boilerplate_inside_code_fence_needs_far_more_repeats",
      "test_json_with_varying_values_is_not_flagged", "test_normal_prose_never_triggers",
      "test_edit_then_rerun_is_not_a_loop", "test_rereading_a_changing_file_is_legitimate",
      "test_exploration_of_many_different_files_is_not_stagnation"]),
    (9, "Two concurrent sessions", ["test_two_concurrent_sessions_keep_independent_state",
                                    "test_same_tool_calls_in_two_sessions_do_not_add_up"]),
    (10, "Loop in one session while another generates normally",
     ["test_loop_in_one_session_while_other_generates_normally", "test_intervention_in_one_session_does_not_reset_the_other",
      "test_events_without_session_id_never_trigger_automatic_intervention"]),
    (11, "Hermes integration unavailable", ["test_hermes_integration_unavailable_null_adapter",
                                            "test_failed_push_keeps_directive_and_retries_sooner",
                                            "test_unreachable_webhook_is_handled_off_thread"]),
    (12, "Recovery after an intervention", ["test_recovery_after_intervention", "test_detectors_are_reset_after_an_intervention",
                                            "test_escalation_redirect_redirect_interrupt"]),
    (13, "Service restart and configuration persistence",
     ["test_config_session_modes_and_token_survive_restart", "test_config_file_is_valid_json_and_written_atomically",
      "test_invalid_config_file_fails_fast"]),
]


def main():
    xml = Path(tempfile.mkdtemp()) / "junit.xml"
    p = subprocess.run([sys.executable, "-m", "pytest", "-q", f"--junitxml={xml}", "-p", "no:cacheprovider"],
                       cwd=str(ROOT), capture_output=True, text=True)
    tree = ET.parse(xml).getroot()
    cases = []
    for tc in tree.iter("testcase"):
        status = "passed"
        if tc.find("failure") is not None or tc.find("error") is not None:
            status = "FAILED"
        elif tc.find("skipped") is not None:
            status = "skipped"
        cases.append((tc.get("classname", "").split(".")[-1], tc.get("name"), status, float(tc.get("time", 0))))
    by = {n: s for _, n, s, _ in cases}
    total = len(cases)
    passed = sum(1 for c in cases if c[2] == "passed")
    failed = sum(1 for c in cases if c[2] == "FAILED")
    skipped = sum(1 for c in cases if c[2] == "skipped")

    res = ROOT / "reports" / "resource_measurement.json"
    resource = json.loads(res.read_text()) if res.exists() else None
    env = ROOT / "reports" / "environment.sandbox.json"
    envj = json.loads(env.read_text()) if env.exists() else None

    L = ["# TEST_REPORT", "",
         f"Generated by `tools/make_test_report.py` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}.",
         "", "## Environment of this run", "",
         f"* Python {platform.python_version()} on {platform.system()} {platform.release()} ({platform.machine()}), "
         f"{__import__('os').cpu_count()} CPU(s) - an isolated Linux sandbox, **not** the target Windows 11 / WSL machine.",
         "* Standard library only; `pytest` was installed inside a throw-away virtual environment.",
         "* The sandbox contains **no Hermes installation and no llama.cpp/Strata server** "
         f"(`reports/environment.sandbox.json`: hermes found = {envj['hermes']['found'] if envj else 'n/a'}, "
         f"llama endpoint health = {envj['llama_endpoint']['health']['status'] if envj else 'n/a'}). "
         "Nothing in this report says anything about Hermes' own API.",
         "", "## Result", "",
         f"**{passed} passed, {failed} failed, {skipped} skipped** ({total} tests). Command: `python -m pytest`.", ""]
    if failed:
        L += ["### Failures", ""] + [f"* `{c[0]}::{c[1]}`" for c in cases if c[2] == "FAILED"] + [""]
    L += ["## Requirement coverage (section 11 of the brief)", "",
          "| # | Requirement | Tests | Result |", "|---|---|---|---|"]
    for num, title, names in REQUIREMENTS:
        st = [by.get(n, "MISSING") for n in names]
        res_txt = "PASS" if all(s == "passed" for s in st) else "FAIL: " + ", ".join(f"{n}={s}" for n, s in zip(names, st) if s != "passed")
        L.append(f"| {num} | {title} | {len(names)} | {res_txt} |")
    L += ["", "Test names per requirement are listed in `REQUIREMENTS` inside `tools/make_test_report.py`.", ""]
    L += ["## All tests", "", "| File | Test | Result | Time (s) |", "|---|---|---|---|"]
    for f, n, s, t in cases:
        L.append(f"| {f} | `{n}` | {s} | {t:.2f} |")
    L.append("")
    if resource:
        L += ["## Resource consumption (measured)", "",
              f"Measured with `tools/simulate.py` (Python {resource['python']}, {resource['platform']}, "
              f"{resource['cpu_count']} CPU core(s), {resource['sessions']} concurrent sessions). "
              "CPU = the **service process only** (OS counters), as a percentage of **one core**; "
              "the load generator ran on the same single core. GPU use is zero by construction (no inference, no GPU libraries).", "",
              "| Phase | Seconds | Events/s | Service CPU (% of one core) | RSS at end (MB) |", "|---|---|---|---|---|"]
        for key, label in (("idle", "Idle (no traffic)"), ("normal_load", "Normal load: 2 sessions at ~50 tok/s each"),
                           ("loop_in_session_0", "One session looping text"), ("burst_max_rate", "Burst: events as fast as possible")):
            r = resource[key]
            L.append(f"| {label} | {r['seconds']} | {r['events_per_s']} | {r['service_cpu_percent_of_one_core']} | {r['rss_mb_end']} |")
        L += ["", f"RSS right after start: {resource['rss_mb_after_start']} MB; peak during the whole run: {resource['rss_mb_peak']} MB.",
              f"Service counters after the run: `{json.dumps(resource.get('service_counters', {}))}`.", "",
              "Targets from the brief: CPU < 1 %, RAM < 60 MB. **Met in this sandbox** for idle, normal load and the loop phase "
              "(burst mode deliberately exceeds normal traffic by ~600x and is shown only as headroom). "
              "These numbers come from Linux/CPython 3.12 and **must be re-measured on the target machine**: "
              "`python tools/simulate.py --duration 60`. On Windows the simulator needs `pip install psutil` inside the project venv.", ""]
    L += ["## Not tested / not verified", "",
          "* **Hermes**: no real Hermes was available. No Hermes API, hook, session id or session-control call was exercised. "
          "Only the watchdog's own contract (HTTP API, `queue` pull adapter, `webhook` push adapter against a local example receiver) is tested.",
          "* **Strata / llama.cpp log format**: the log tailer is tested against synthetic lines in the usual llama.cpp format, not against a real Strata log.",
          "* **Windows 11 and WSL**: PowerShell scripts (`*.ps1`) were written but never executed; the Windows memory probe (`ctypes`/psapi) was never executed; "
          "Windows process-stop semantics are untested. POSIX scripts were executed (start, health, stop) on Linux.",
          "* **Python 3.14.7**: not available in the sandbox. The code uses only the standard library and no removed modules; it ran on 3.12.3.",
          "* **Real-world false-positive rate**: the false-positive tests use synthetic prose, code and JSON. Behaviour on your real Qwen reasoning traces is unmeasured; "
          "run in `observe` mode first and review `logs/watchdog.jsonl`.",
          "* **Long-duration soak** (hours/days) and memory growth over time were not tested beyond the ~2 minute simulation; all buffers are bounded by configuration.",
          ""]
    out = ROOT / "TEST_REPORT.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"{passed} passed, {failed} failed, {skipped} skipped -> {out}")
    if failed or "MISSING" in "\n".join(L):
        print(p.stdout[-3000:])
        sys.exit(1)


if __name__ == "__main__":
    main()
